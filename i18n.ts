import { AchievementId, Language } from './types';

export const SUPPORTED_LANGUAGES: Language[] = ['fa', 'en', 'nl', 'de', 'fr', 'ar', 'tr', 'pl', 'uk'];

export const RTL_LANGUAGES: ReadonlySet<Language> = new Set<Language>(['fa', 'ar']);

export const LOCALE_MAP: Record<Language, string> = {
  fa: 'fa-IR',
  en: 'en-US',
  nl: 'nl-NL',
  de: 'de-DE',
  fr: 'fr-FR',
  ar: 'ar-SA',
  tr: 'tr-TR',
  pl: 'pl-PL',
  uk: 'uk-UA'
};

export function isRTLLanguage(language: Language): boolean {
  return RTL_LANGUAGES.has(language);
}

export function formatTemplate(template: string, vars: Record<string, string | number>): string {
  return Object.entries(vars).reduce(
    (acc, [key, value]) => acc.replace(new RegExp(`\\{${key}\\}`, 'g'), String(value)),
    template
  );
}

export function formatLocalizedDate(date: Date, language: Language): string {
  try {
    return date.toLocaleDateString(LOCALE_MAP[language] || 'en-US');
  } catch {
    return date.toLocaleDateString('en-US');
  }
}

export function syncDocumentLanguage(language: Language): void {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = language;
  document.documentElement.dir = isRTLLanguage(language) ? 'rtl' : 'ltr';
}

